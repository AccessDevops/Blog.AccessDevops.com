#!/usr/bin/env python3
"""Self-host Inter + JetBrains Mono (woff2, latin + latin-ext only).

Removes the render-blocking request to fonts.googleapis.com: in a headless
browser without a warm font cache that request can stall page load forever
(no stable frame -> screenshots hang), and for real visitors it costs a
third-party RTT before first paint.

Run from the repo root: python3 assets-src/fetch_fonts.py
Outputs public/fonts/*.woff2 and assets/css/fonts.css
"""
import os, re, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, "public", "fonts")
CSS_OUT = os.path.join(ROOT, "assets", "css", "fonts.css")
UA = ("Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) "
      "Chrome/120.0.0.0 Safari/537.36")
KEEP = {"latin", "latin-ext"}
URL = ("https://fonts.googleapis.com/css2?family=Inter:wght@400;500;600;700"
       "&family=JetBrains+Mono:wght@400;500&display=swap")

os.makedirs(OUT_DIR, exist_ok=True)
req = urllib.request.Request(URL, headers={"User-Agent": UA})
css = urllib.request.urlopen(req, timeout=30).read().decode()

# Google emits "/* subset */\n@font-face{...}" blocks
blocks = re.split(r"/\*\s*([a-z0-9-]+)\s*\*/", css)
faces = []
for i in range(1, len(blocks), 2):
    subset, body = blocks[i], blocks[i + 1]
    if subset not in KEEP:
        continue
    fam = re.search(r"font-family:\s*'([^']+)'", body)
    wght = re.search(r"font-weight:\s*(\d+)", body)
    src = re.search(r"url\((https://fonts\.gstatic\.com/[^)]+\.woff2)\)", body)
    rng = re.search(r"unicode-range:\s*([^;]+);", body)
    if not (fam and wght and src):
        continue
    name = f"{fam.group(1).replace(' ', '')}-{wght.group(1)}-{subset}.woff2"
    path = os.path.join(OUT_DIR, name)
    if not os.path.exists(path):
        data = urllib.request.urlopen(
            urllib.request.Request(src.group(1), headers={"User-Agent": UA}), timeout=30).read()
        open(path, "wb").write(data)
    faces.append((fam.group(1), wght.group(1), subset, name, rng.group(1).strip() if rng else None))
    print(f"{name:<34} {os.path.getsize(path)//1024} KB")

lines = ["/* Self-hosted webfonts — generated by assets-src/fetch_fonts.py, do not edit. */"]
for fam, wght, subset, name, rng in faces:
    lines.append("@font-face {")
    lines.append(f"  font-family: '{fam}';")
    lines.append("  font-style: normal;")
    lines.append(f"  font-weight: {wght};")
    lines.append("  font-display: swap;")
    lines.append(f"  src: url('/fonts/{name}') format('woff2');")
    if rng:
        lines.append(f"  unicode-range: {rng};")
    lines.append("}")
open(CSS_OUT, "w").write("\n".join(lines) + "\n")
print(f"\n{len(faces)} faces -> {CSS_OUT}")
